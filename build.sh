#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
DIST="$ROOT/dist"
PASSWORD="${PASSWORD:-sfera-view}"

if command -v shasum >/dev/null 2>&1; then
  HASH="$(printf '%s' "$PASSWORD" | shasum -a 256 | awk '{print $1}')"
elif command -v sha256sum >/dev/null 2>&1; then
  HASH="$(printf '%s' "$PASSWORD" | sha256sum | awk '{print $1}')"
else
  HASH="$(python3 - <<PY
import hashlib
print(hashlib.sha256(b"""$PASSWORD""".encode()).hexdigest())
PY
)"
fi

rm -rf "$DIST"
mkdir -p "$DIST/js" "$DIST/assets" "$DIST/fonts"

cp "$ROOT/index.html" "$ROOT/sfera.html" "$ROOT/kit.html" "$ROOT/login.html" "$DIST/"
cp "$ROOT/styles.css" "$ROOT/tokens.css" "$ROOT/sfera.css" "$ROOT/login.css" "$DIST/"
cp "$ROOT/js/auth.js" "$DIST/js/"
cp -R "$ROOT/assets/." "$DIST/assets/"
cp -R "$ROOT/fonts/." "$DIST/fonts/"

cat > "$DIST/js/auth-config.js" <<EOF
/* Generated by ./build.sh — do not edit by hand */
window.PORTFOLIO_AUTH = {
  hash: "$HASH",
  storageKey: "portfolio_auth_v1",
};
EOF

# Keep source config in sync so local preview outside dist also works.
cp "$DIST/js/auth-config.js" "$ROOT/js/auth-config.js"

# Drop macOS junk from the published tree.
find "$DIST" -name '.DS_Store' -delete

cat > "$DIST/.nojekyll" <<EOF
EOF

echo "Built $DIST"
echo "Password: $PASSWORD"
echo "Open:   ruby -run -e httpd dist -p 8765"
echo "Then:   http://127.0.0.1:8765/login.html"
